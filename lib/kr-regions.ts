/**
 * 지역 하나에 붙여 볼 표현들.
 *
 * 한 업소가 어떤 이름을 쓰는지는 제각각입니다 — 간판은 "게임랜드" 인데 네이버에
 * 등록된 업체명은 "○○오락실" 인 경우가 흔합니다. 표현을 여러 개 돌려야 빠지는
 * 곳이 줄어듭니다. 대신 질의 수가 (지역 수 × 이 배열 길이) 로 늘어납니다.
 */
export const ARCADE_KEYWORDS = ['오락실', '게임센터', '게임랜드', '아케이드게임'] as const;

/**
 * 전국 질의 목록. "서울 강남구 오락실" 같은 문자열이 됩니다.
 *
 * 순서가 중요합니다 — 하루 한도에 걸려 중단되면 **앞에서부터 끝낸 만큼만** 남고
 * 다음 날 그 뒤를 잇습니다. 지역을 바깥 루프로 두면 특정 지역만 4개 표현이 모두
 * 끝난 상태가 되어, 중단 지점이 "어느 지역까지" 로 깔끔하게 읽힙니다.
 * (표현을 바깥에 두면 전국이 '오락실' 만 끝난 어정쩡한 상태가 됩니다)
 */
export function buildArcadeQueries(
  regions: Readonly<Record<string, readonly string[]>> = KR_REGIONS,
  keywords: readonly string[] = ARCADE_KEYWORDS,
): string[] {
  const out: string[] = [];
  for (const [sido, sigungu] of Object.entries(regions)) {
    for (const gu of sigungu) {
      for (const kw of keywords) {
        // 세종은 '세종 세종시' 가 되므로 시도명을 겹쳐 쓰지 않습니다.
        const place = gu.startsWith(sido) ? gu : `${sido} ${gu}`;
        out.push(`${place} ${kw}`);
      }
    }
  }
  return out;
}

/** 전국 시·군·구 수 (질의 수 계산·표시용) */
export function countRegions(
  regions: Readonly<Record<string, readonly string[]>> = KR_REGIONS,
): number {
  return Object.values(regions).reduce((n, list) => n + list.length, 0);
}
