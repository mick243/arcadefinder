/**
 * `db/*.sql` → `prisma/migrations/` 변환기.
 *
 *   node scripts/prisma-migrations-build.mjs            생성·갱신
 *   node scripts/prisma-migrations-build.mjs --check    어긋난 것만 출력 (쓰지 않음)
 *   node scripts/prisma-migrations-build.mjs --prune    목록에 없는 폴더까지 지움
 *
 * 왜 손으로 만들지 않고 생성하나:
 *   적용 순서의 정본은 `scripts/db-files.mjs` 하나다 (lib/db.ts 와 대조하는 테스트가
 *   이미 있다 — tests/db-lists.test.ts). 마이그레이션 폴더를 손으로 만들면 정본이
 *   둘이 되고, 2026-08-24 에 030~036 이 빠진 채 이력만 남았던 사고가 그대로 재현된다.
 *   여기서 생성하면 목록이 곧 폴더다. tests/prisma-migrations.test.ts 가 대조한다.
 *
 * 폴더 이름: `<합성 타임스탬프>_<원본 파일명>`.
 *   Prisma 는 폴더 이름을 **사전순**으로 적용한다. 기존 파일들은 실제로 만들어진
 *   시각을 모르고(커밋 날짜 ≠ 적용 순서), 순서만 지키면 되므로 2026-01-01 00:00 에서
 *   1분씩 더한 합성 시각을 쓴다. 이름 뒤에 원본 파일명이 그대로 남아 어느 파일인지
 *   바로 보인다.
 *
 * ⚠ **이미 적용된 마이그레이션의 내용은 바뀌면 안 된다.** Prisma 는 적용 시점의
 *   체크섬(sha256)을 `_prisma_migrations` 에 남기고, 파일이 달라지면 `migrate deploy`
 *   가 거부한다. 즉 `db/` 의 옛 파일을 고치는 순간 이미 배포된 DB 가 막힌다 —
 *   지금 규칙("적용된 마이그레이션은 고치지 않고 새 파일을 만든다")과 같은 규칙이고,
 *   Prisma 쪽이 그걸 강제해 줄 뿐이다.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MIGRATION_FILES, SCHEMA_FILES } from './db-files.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DB_DIR = path.join(root, 'db');
export const MIGRATIONS_DIR = path.join(root, 'prisma', 'migrations');

/**
 * 적용 순서 = 스키마 그룹 → 마이그레이션. lib/db.ts applySchema 와 같은 순서다.
 *
 * **`views.sql` 은 일부러 뺐다.** 뷰는 지금도 마이그레이션이 아니라 "기동마다 다시
 * 적용하는 파생 객체" 이고(db/views.sql 머리말), 그 성질을 Prisma 로 옮기면 두 가지가
 * 깨진다:
 *   1. 뷰는 항상 **마지막**이어야 하는데(migrate-039 가 만든 컬럼을 참조한다) 폴더
 *      이름이 순번이라 새 마이그레이션이 생길 때마다 뷰 폴더 이름이 밀린다. 이미
 *      적용된 DB 에는 옛 이름이 남아 `migrate status` 가 계속 어긋났다고 말한다.
 *   2. 집계식을 고칠 때 파일 하나만 고치면 되던 것이, 새 마이그레이션 파일을 만들어야
 *      하는 일로 바뀐다.
 * 그래서 뷰는 그대로 둔다 — Prisma 경로도 기동할 때 적용하고(lib/db.ts), 손으로는
 * `npm run db:views` 로 적용한다. 데이터가 없는 객체라 몇 번을 다시 만들어도 안전하다.
 *
 * ⚠ 이 목록은 **덧붙이기만** 한다. 중간에 끼워 넣으면 그 뒤 폴더 이름이 전부 밀리고,
 *   이미 적용된 DB 에서 이름이 어긋난다.
 */
export const ORDERED_FILES = [...SCHEMA_FILES, ...MIGRATION_FILES];

/** 합성 타임스탬프의 기준점. 의미 없는 값 — 순서만 지키면 된다. */
const BASE_MS = Date.UTC(2026, 0, 1, 0, 0, 0);

/** `migration_lock.toml` — Prisma 가 provider 가 바뀌었는지 보는 파일이다. */
export const MIGRATION_LOCK = `# Please do not edit this file manually
# It should be added in your version-control system (e.g., Git)
provider = "postgresql"
`;

export function folderName(file, index) {
  const stamp = new Date(BASE_MS + index * 60_000)
    .toISOString()
    .replace(/[-:T]/g, '')
    .slice(0, 14);
  const slug = file.replace(/\.sql$/, '').replace(/[^a-zA-Z0-9]+/g, '_');
  return `${stamp}_${slug}`;
}

/**
 * 스키마 파일 앞머리의 `DROP TABLE IF EXISTS … CASCADE;` 를 주석으로 바꾼다.
 *
 * 그 줄들은 `db:init`(파괴적 재생성)을 위한 것이다. 빈 DB 에 처음 적용될 때는
 * 아무 일도 하지 않으므로 지워도 결과가 같지만, **이미 데이터가 있는 DB 에 실수로
 * `migrate deploy` 를 돌렸을 때** 결과가 갈린다:
 *   그대로 두면 → 테이블을 지우고 다시 만든다 (조용한 데이터 손실)
 *   주석 처리하면 → "relation already exists" 로 즉시 멈춘다
 * 베이스라인(scripts/prisma-baseline.mjs)을 빠뜨린 DB 는 반드시 있을 것이고,
 * 그때 시끄럽게 실패하는 쪽이 낫다.
 *
 * `migrate-*.sql` 의 DROP 은 건드리지 않는다 — 거의 다 그 파일이 만든 임시 테이블을
 * 치우는 것이라(예: `DROP TABLE ez2dj_aeic_charts;`) 지우면 마이그레이션이 깨진다.
 * `views.sql` 의 `DROP VIEW` 도 그대로 둔다 (뷰는 데이터를 갖지 않는다).
 */
export function stripInitDrops(sql) {
  return sql.replace(
    /^[ \t]*DROP[ \t]+TABLE[ \t]+IF[ \t]+EXISTS[ \t][^;]*;[ \t]*$/gim,
    (line) => `-- [prisma-migrations-build] db:init 전용 — 주석 처리: ${line.trim()}`,
  );
}

export function migrationSql(file) {
  const raw = fs.readFileSync(path.join(DB_DIR, file), 'utf8');
  const body = SCHEMA_FILES.includes(file) ? stripInitDrops(raw) : raw;
  const header =
    `-- 원본: db/${file}\n` +
    `-- 이 파일은 scripts/prisma-migrations-build.mjs 가 생성합니다. 손으로 고치지 마세요 —\n` +
    `-- 내용을 바꾸면 체크섬이 달라져 이미 적용된 DB 에서 migrate deploy 가 거부합니다.\n\n`;
  // 줄바꿈을 LF 로 고정한다 — 체크섬이 체크아웃한 장비의 autocrlf 에 따라 달라지면 안 된다.
  return (header + body).replace(/\r\n/g, '\n');
}

/** Prisma 가 `_prisma_migrations.checksum` 에 넣는 값과 같은 방식 (sha256 hex) */
export function checksum(sql) {
  return crypto.createHash('sha256').update(sql, 'utf8').digest('hex');
}

/** 생성될 마이그레이션 전체. 파일을 읽기만 한다. */
export function plan() {
  return ORDERED_FILES.map((file, i) => {
    const sql = migrationSql(file);
    return { file, folder: folderName(file, i), sql, checksum: checksum(sql) };
  });
}

function main() {
  const check = process.argv.includes('--check');
  const prune = process.argv.includes('--prune');
  const items = plan();
  const expected = new Set(items.map((m) => m.folder));

  const stale = fs.existsSync(MIGRATIONS_DIR)
    ? fs
        .readdirSync(MIGRATIONS_DIR, { withFileTypes: true })
        .filter((e) => e.isDirectory() && !expected.has(e.name))
        .map((e) => e.name)
    : [];

  const changed = [];
  for (const m of items) {
    const file = path.join(MIGRATIONS_DIR, m.folder, 'migration.sql');
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === m.sql) continue;
    changed.push({ folder: m.folder, kind: current === null ? '새로 만듦' : '내용이 다름' });
    if (!check) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, m.sql);
    }
  }

  const lockPath = path.join(MIGRATIONS_DIR, 'migration_lock.toml');
  if (!check) {
    fs.mkdirSync(MIGRATIONS_DIR, { recursive: true });
    if (!fs.existsSync(lockPath) || fs.readFileSync(lockPath, 'utf8') !== MIGRATION_LOCK) {
      fs.writeFileSync(lockPath, MIGRATION_LOCK);
    }
  }

  for (const c of changed) console.log(`  ${c.kind === '새로 만듦' ? '+' : '~'} ${c.folder} — ${c.kind}`);
  for (const s of stale) {
    console.log(`  ? ${s} — db/ 목록에 없는 폴더${prune && !check ? ' (지웁니다)' : ''}`);
    if (prune && !check) fs.rmSync(path.join(MIGRATIONS_DIR, s), { recursive: true, force: true });
  }

  console.log(
    check
      ? `대조: 마이그레이션 ${items.length}개 · 어긋남 ${changed.length}개 · 목록 밖 ${stale.length}개`
      : `생성: 마이그레이션 ${items.length}개 · 쓴 것 ${changed.length}개 · 목록 밖 ${stale.length}개`,
  );

  // --check 는 CI·훅에서 쓰라고 종료 코드로도 알린다.
  if (check && (changed.length || stale.length)) process.exit(1);
}

// 테스트는 함수만 가져다 쓴다 — import 했다고 파일을 쓰면 안 된다.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
