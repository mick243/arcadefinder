-- ============================================================
-- 013 · 시드로 들어간 Pump It Up S15 · S16 · D18 서열표 제거
--
-- ─── 왜 ──────────────────────────────────────────────────
-- 이 세 서열표는 seed-tier.sql 이 집계 파이프라인 시연용으로 넣은 **가상
-- 데이터**입니다 (곡은 실제 수록곡이지만 등급 배치는 만들어낸 투표의 결과).
-- 012 로 실제 서열표(S1)가 들어왔으므로, 가상 데이터가 같은 게임의 레벨
-- 선택기에 섞여 있으면 어느 쪽이 실제인지 구분할 수 없습니다.
--
-- ─── 무엇이 지워지는가 ───────────────────────────────────
-- machine_id = 1 (Pump It Up) 의 (S,15) · (S,16) · (D,18) 채보 24개.
-- FK 가 모두 ON DELETE CASCADE 라 딸린 것도 함께 사라집니다:
--   · clear_records     (클리어 기록)
--   · difficulty_votes  (체감 난이도 투표 — clear_records 를 복합 FK 로 참조)
--   · chart_comments    (채보 평가. seed-community.sql 이 이 채보들에 8건을 넣습니다)
--
-- ⚠ **곡(songs)은 지우지 않습니다.** Bee · Canon-D · Napalm 등은 실제 수록곡이고
--   005 의 곡 목록에도 들어 있습니다. 채보가 없어질 뿐 곡 카탈로그에는 남아야
--   합니다 (챗봇·검색이 곡 목록을 참조합니다). 특히 `Bad Apple!! feat. nomico`
--   는 S15 와 S1 양쪽에 채보가 있어서, 곡을 지우면 012 가 만든 S1 채보까지
--   CASCADE 로 날아갑니다. 아래 WHERE 가 mode·level 을 함께 걸어 S1 은 남습니다.
--
-- ⚠ **players 도 지우지 않습니다.** 012 가 투표자로 쓰는 계정입니다.
--
-- ─── SOUND VOLTEX 는 건드리지 않습니다 ───────────────────
-- seed-community.sql 이 넣은 사볼 EXH17 · MXM18 채보 15개도 같은 성격의 가상
-- 데이터이지만, 요청 범위(Single 15·16, Double 18)가 아니고 지우면 사볼 서열표가
-- 통째로 비어 게임 선택기에서 고를 수 없는 항목이 됩니다. 그대로 둡니다.
--
-- ─── seed-tier.sql 을 고치지 않는 이유 ───────────────────
-- 새 DB 는 시드가 이 채보들을 만든 뒤 이 파일이 지우므로 결과가 같습니다.
-- 시드를 직접 고치면 seed-community.sql 의 채보 평가 8건이 조인에 실패해 조용히
-- 사라지고(그쪽 VALUES 도 함께 손봐야 함), 이미 적용된 DB 와 새 DB 의 이력이
-- 갈라집니다. 006(곡 삭제) · 010(사업형태 제거) 과 같은 방식입니다 —
-- 시드는 그때의 상태로 두고, 고치는 것은 마이그레이션이 합니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- 지울 것이 없으면 0행이 지워집니다.
--
-- 되돌리려면: 이 파일은 되돌릴 수 없습니다 (투표·평가가 함께 사라짐).
--   복구가 필요하면 npm run db:reset 후 이 파일을 MIGRATION_FILES 에서 빼세요.
-- ============================================================

DELETE FROM charts c
USING songs s
WHERE s.id = c.song_id
  AND s.machine_id = 1
  AND (c.mode, c.level) IN (('S', 15), ('S', 16), ('D', 18));
