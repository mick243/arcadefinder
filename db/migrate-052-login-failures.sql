-- ============================================================
-- 로그인·가입·본인확인 시도 제한을 프로세스 밖으로
--
-- 지금까지 실패 횟수는 `lib/auth.ts` 의 `Map` 한 개, 즉 **그 프로세스의
-- 메모리**에만 있었습니다. 코드 주석이 그 한계를 이미 적어 두었습니다 —
-- "서버가 여러 대면 대수만큼 여유가 생기고 재시작하면 풀립니다".
--
-- 그 "여러 대" 가 이제 현실입니다. 프로세스를 2개로 늘리면(PERFORMANCE.md 4부 15절)
-- 카운터도 2개가 되어 **IP 당 8회 제한이 실질 16회**가 됩니다. 프로세스를
-- 늘리는 것이 곧 방어를 8배 느슨하게 만드는 셈이라, 다중 프로세스로 가려면
-- 이 표가 선택이 아니라 전제입니다.
--
--   key   : 무엇을 세는가. 지금 쓰는 모양은 셋입니다.
--             `1.2.3.4`            로그인 (IP)
--             `signup:1.2.3.4`     가입 — 로그인과 통을 나눕니다. 남의 가입
--                                  실패로 기존 사용자가 잠기면 안 됩니다.
--             `account:42`         개인정보 수정의 비밀번호 재확인 (계정 단위)
--   count : 창 안에서 누적된 실패 횟수
--   until : 이 시각까지가 한 창. 실패할 때마다 뒤로 밀립니다(원래 동작과 같음)
--
-- **Redis 가 아니라 Postgres 인 이유** — 이미 있는 것이기 때문입니다. Redis 를
-- 들이면 운영해야 할 저장소가 하나 늘고, 이 경로는 초당 수천 번 오는 곳이
-- 아닙니다(실패한 시도 1회당 쿼리 1회). 트래픽이 그만큼 커지면 그때 옮길
-- 자리이고, 그때도 이 파일의 함수 세 개만 바뀝니다.
--
-- 낡은 행은 따로 배치를 두지 않고 실패를 기록할 때 함께 지웁니다
-- (lib/reports.ts purgeExpiredQueueReports 와 같은 방식) — 쓰기가 드물어서
-- 그 김에 치우는 것으로 충분합니다.
--
-- ⚠ 여러 번 실행해도 안전해야 합니다 (lib/db.ts runMigrations 주석 참고).
--
-- ─── 번호에 관하여 ──────────────────────────────────────────
-- `claude/mfa-jwt-token-status` 에서 같은 이름(052)으로 쓰여진 것을 R1 병합 때
-- 가져왔습니다. **번호와 이름을 그대로 둔 것이 중요합니다** — 저쪽이 들어올 때
-- 한 파일로 합쳐지므로 같은 DDL 이 두 이름으로 적용되지 않습니다. 본문(DDL)은
-- 같고 머리말만 다릅니다(저쪽은 "8프로세스 → 64회", 이 브랜치의 권고 구성은
-- 2프로세스라 "16회" 로 고쳤습니다). 합칠 때는 이쪽 문구를 쓰세요.
--
-- 저쪽의 050-player-email · 051-email-verification 은 이 브랜치에 없습니다.
-- 그 번호를 비워 둔 이유는 migrate-053 머리말에 적어 뒀습니다.
-- ============================================================

CREATE TABLE IF NOT EXISTS login_failures (
  key        TEXT PRIMARY KEY,
  count      INTEGER NOT NULL,
  until      TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 낡은 행을 훑어 지울 때 씁니다.
CREATE INDEX IF NOT EXISTS login_failures_until_idx ON login_failures (until);
