-- ============================================================
-- 044 · 서열표의 "채보 데이터 기준" 문구를 게임별로
--
-- ─── 왜 ──────────────────────────────────────────────────
-- TierBoardView 에 "해당 서열표는 PHOENIX 2를 기준으로 작성되었습니다" 가
-- 하드코딩돼 있어서 **사볼 서열표에도 그대로 떴습니다.** PHOENIX 2 는 펌프
-- 버전명이라 사볼에서는 틀린 문구입니다.
--
-- 펌프에는 맞는 말입니다 — 채보 목록을 PHOENIX 2 기준 자료에서 수집했습니다
-- (migrate-033 주석의 출처 참고). 그래서 문구를 지우는 게 아니라 **게임이
-- 자기 기준을 들고 있게** 합니다. 등급 수(tier_grades)와 임계값을 이미 게임별로
-- 두고 있으므로 같은 자리에 둡니다.
--
-- NULL 이면 화면이 그 줄을 아예 그리지 않습니다. 사볼은 아직 어느 버전 기준으로
-- 채보를 모을지 정해지지 않았으니 비워 둡니다 — 정해지면 이 값만 채우면 됩니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- ADD COLUMN IF NOT EXISTS + machine_id 를 명시한 UPDATE.
-- ============================================================

ALTER TABLE tier_settings ADD COLUMN IF NOT EXISTS chart_basis TEXT;

COMMENT ON COLUMN tier_settings.chart_basis IS
  '채보 목록을 어느 버전 기준으로 모았는지. NULL 이면 화면에 표시하지 않는다.';

-- 펌프(1)만 채웁니다. 사볼(3)은 NULL 유지 → 화면에서 문구가 사라집니다.
UPDATE tier_settings
   SET chart_basis = 'PHOENIX 2'
 WHERE machine_id = 1;
