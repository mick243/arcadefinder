-- ============================================================
-- 컨디션 제보는 1달, 기종 변동은 항시.
--
-- 세 종류의 제보가 서로 다른 속도로 낡습니다.
--
--   대기(queue)      4시간 — 지나면 **행까지 지웁니다**. 20시간 전 "대기 5명"
--                            은 되돌아볼 값이 아니라 그냥 틀린 값입니다.
--   컨디션(condition) 1달  — 행은 남기고 **집계에서만** 뺍니다. 발판 상태는
--                            천천히 변하지만 반년 전 평가가 오늘 값에 섞이면
--                            고쳐 놓은 기체가 계속 나쁜 점수를 답니다.
--   기종 변동         영구 — 지우지도, 창으로 자르지도 않습니다.
--   (presence/absence)      "이 오락실에 이 게임이 있다/없다" 는 시간이 지나도
--                            틀린 말이 되지 않고, 뒤집는 것은 **반대 제보**이지
--                            시간이 아닙니다 (lib/reports.ts applyPresence 는
--                            반대 제보가 마지막으로 들어온 뒤로만 셉니다).
--
-- 60일 → 30일로 좁히는 이유: 두 달 전 컨디션은 그 사이 기체가 정비됐는지
-- 아닌지를 말해 주지 못합니다. 한 달이면 "요즘 상태" 라고 부를 수 있는 한계선이고,
-- 그보다 길게 잡으면 제보를 새로 해도 옛 평가에 묻혀 값이 잘 안 움직입니다.
--
-- 창을 좁혀도 **제보 행은 그대로 남습니다** — 전국 피드와 오락실 상세의
-- '최근 제보' 목록에는 계속 보이고, 집계(cabinet_condition 뷰)에서만 빠집니다.
-- 창을 다시 넓히면 옛 제보가 그대로 되살아납니다.
--
-- 뷰(db/views.sql cabinet_condition)는 이 설정값을 읽으므로 고칠 것이 없습니다.
-- 서버가 뜰 때마다 DROP → CREATE 되니 다음 기동에 새 값이 그대로 반영됩니다.
-- ============================================================

-- 기본값도 함께 옮깁니다. 새로 만드는 DB 가 옛 값으로 시작하면, 같은 코드가
-- DB 마다 다른 기간으로 도는 상태가 됩니다.
ALTER TABLE report_settings
  ALTER COLUMN condition_window_days SET DEFAULT 30;

-- 운영자가 콘솔에서 일부러 다른 값으로 바꿔 둔 경우는 건드리지 않습니다.
-- 옛 기본값(60)에 그대로 있는 행만 옮깁니다.
UPDATE report_settings
SET condition_window_days = 30
WHERE id = 1 AND condition_window_days = 60;
