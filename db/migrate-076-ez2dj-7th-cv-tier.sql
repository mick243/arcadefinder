-- ─── 5) 채보 1,384개 ──────────────────────────────────────
-- 가로 16칸을 세로로 펼칩니다. `-` 는 채보가 없다는 뜻이라 버립니다.
-- `-HARD-` 줄(as_hd)은 난이도를 HD 로 바꿉니다 — 머리말 참고.
CREATE TEMP TABLE ez2dj_cv_charts AS
SELECT COALESCE(a.canon, t.title) AS title,
       v.mode,
       CASE WHEN COALESCE(a.as_hd, FALSE) THEN 'HD' ELSE v.difficulty END AS difficulty,
       CASE WHEN v.val = '?' THEN NULL ELSE v.val::int END AS level
FROM ez2dj_cv t
LEFT JOIN ez2dj_cv_alias a ON a.wiki = t.title
CROSS JOIN LATERAL (VALUES
  ('RUBY',  'NM',  t.ruby_n),
  ('RUBY',  'HD',  t.ruby_h),
  ('5ST',   'EZ',  t.s5e),
  ('5ST',   'NM',  t.s5n),
  ('5ST',   'HD',  t.s5h),
  ('5ST',   'SHD', t.s5s),
  ('7ST',   'EZ',  t.s7e),
  ('7ST',   'NM',  t.s7n),
  ('7ST',   'HD',  t.s7h),
  ('7ST',   'SHD', t.s7s),
  ('CLUB',  'NM',  t.club_n),
  ('CLUB',  'HD',  t.club_h),
  ('SPACE', 'NM',  t.sp_n),
  ('SPACE', 'HD',  t.sp_h),
  ('CATCH', 'NM',  t.cat_n),
  ('TURN',  'NM',  t.turn_n)
) AS v(mode, difficulty, val)
WHERE v.val NOT IN ('X', '-', '');

