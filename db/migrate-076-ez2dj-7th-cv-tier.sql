-- EZ2DJ 의 다섯 번째 버전, 흔히 **CV** 로 부르는 것입니다. 곡 162개 · 채보 **1,384개**.
-- 059 · 060 · 074 · 075 와 같이 **투표는 넣지 않아** 전부 '미정' 에서 시작합니다.
--
-- ─── 출처 ────────────────────────────────────────────────
--   나무위키 『EZ2DJ 7th TRAX CLASS R ~CODENAME:VIOLET~/수록곡』 2장 목록
--   https://namu.wiki/w/EZ2DJ 7th TRAX CLASS R ~CODENAME:VIOLET~/수록곡
--
-- 075(2.0)와 같은 16칸 표라 컬럼 구성이 그대로입니다.
--
--   Ruby N·H │ 5Street E·N·H·S │ 7Street E·N·H·S │ Club N·H │ Space N·H │ Catch │ Turn
--
-- 완전한 표이므로 075 처럼 **표 하나를 그대로** 싣습니다. 앞 버전의 채보를
-- 참조하지 않습니다 — 버전끼리 독립이고 화면의 선택기가 가릅니다.
--
-- ─── ⚠ CV 는 곡이 줄어듭니다 (45곡) ──────────────────────
-- 지금까지는 버전이 올라갈 때마다 곡이 늘었습니다(138 → 170 → 181 → 192).
-- CV 는 **162곡으로 줄어듭니다.** 2.0 에 있던 45곡이 표에 없습니다 — 라이선스가
-- 끝난 곡과 정리된 리믹스들입니다 (Catch The Flow · Cellavue · Damnation ·
-- Freedom · Funny Funky · Departure · Anytime · Anemia · 2.14 …).
--
-- 그래서 "앞 버전 곡에 신곡을 더한다" 는 식으로 만들면 **CV 에 없는 곡이 45개
-- 섞입니다.** 문서의 표가 곧 이 버전의 곡 목록이라, 표에 있는 것만 넣습니다.
--
-- ─── 난이도 상한이 18 로 오릅니다 ────────────────────────
-- 060 머리말이 적은 `1~15` 는 7th 시절 이야기입니다. CV 의 표에는 16 · 17 · 18 이
-- 나옵니다 — La Grand Bleu 의 Club HD 가 **18**, 神威 는 5Street HD 부터 Turn 까지
-- 여섯 칸이 17 입니다. `charts_level_check` 가 1~99 라 그대로 들어갑니다.
--
-- ─── ⚠ `-HARD-` 줄 다섯 ──────────────────────────────────
-- 표의 Catch 와 Turn 은 칸이 `N` 하나뿐입니다. 그래서 그 모드에 채보가 둘인 곡은
-- **곡 이름 뒤에 `-HARD-` 를 붙인 줄을 따로** 두었습니다.
--
--   Theme of EZ2DJ 2 -HARD-       Catch 12   (본 줄은 Catch 9)
--   Lucid -HARD-                  Turn  13   (본 줄은 Turn 9)
--   La Grand Bleu -HARD-          Catch 15   (본 줄은 Catch 11)
--   LOKI -HARD-                   Turn  16   (본 줄은 Turn 12)
--   Wars of the Roses 1455 -HARD- Catch 13   (본 줄은 Catch 7)
--
-- 곡을 쪼개지 않고 **같은 곡의 HD 채보**로 넣습니다. 별칭표의 셋째 칸(`as_hd`)이
-- 그 표시이고, 아래 5) 의 CASE 가 그 줄만 난이도를 HD 로 바꿉니다. 다섯 줄 모두
-- 값이 든 칸이 **하나뿐**이라(Catch 아니면 Turn) 다른 칸에 번지지 않습니다.
--
-- ⚠ 075(2.0)는 같은 상황을 **NM 채보 둘**로 넣었습니다. 그 문서는 중복 줄에
--   이름을 안 붙여(`Theme of EZ2DJ 2` 가 두 줄) 어느 쪽이 어려운 것인지 적지
--   않았기 때문입니다. CV 문서는 `-HARD-` 라고 적어 주므로 난이도를 알 수 있어
--   그대로 옮깁니다. 같은 곡이 버전마다 다르게 보이는 것은 출처가 그렇습니다.
--
-- ─── 새로 들어오는 곡 15개 ───────────────────────────────
-- CV 구간의 신곡 12곡 —
--   Akasha · Blood Castle (Remix) · Doll's Garden · Dragon Hunter? ·
--   Eraser Rain for GAIA · For The Top · La Grand Bleu · LOKI ·
--   Step in the Dayz · Tempus Praeterita · Wars of the Roses 1455 · 神威
--
-- 여기에 **2.0 때 넣지 못했던 셋**이 더해집니다. 075 머리말에 적었듯 2nd Life 와
-- Aura 는 2.0 에서 라디오 채널 전용이라 (모드, 레벨)이 없었고, Dance Machine 의
-- yak_won 리믹스는 원곡 하드믹스에 흡수돼 줄이 없었습니다. CV 표에는 셋 다 제
-- 줄이 있어 이제 들어옵니다 (Dance Machine (YK Edit) 는 Club 9 한 칸뿐입니다).
--
-- ─── 곡 이름 ─────────────────────────────────────────────
-- 별칭 35줄. 30줄은 대소문자 · 구두점만 다른 것이고(060 과 같은 기준), 다섯 줄이
-- `값으로 확인` — 글자로는 못 잇고 난이도 값이 같아 같은 곡으로 판정한 것입니다.
--
--   R.D.M. ~Rain Drops in My mind~ = R.D.M.   (부제를 펼쳐 적은 것. 16칸이 모두 같음)
--   Confete (Evening Mix)          = Confete ~ Remix ~
--   Judgement                      = Judgment
--   One Two Three Four             = 1234
--   Theme of EZ2DJ 2               = Ez2Dj (찬가 II)
--
-- ⚠ CV 는 `Look Out` 을 1.0 때의 이름으로 되돌렸습니다 (2.0 은
--   `Look out ~Here comes my love~`). DB 이름과 그대로 맞아 별칭이 필요 없습니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- 행은 전부 ON CONFLICT DO NOTHING. 출처 표에 (곡, 모드, 난이도, 레벨)이 완전히
-- 같은 줄은 없는 것을 확인했습니다 — `-HARD-` 를 HD 로 바꾼 뒤에도 그렇습니다.
-- `level_label` 이 있는 DB 에서도 도는 이유는 059 · 060 머리말과 같습니다.
