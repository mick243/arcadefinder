-- ============================================================
-- 065 · 채보 영상 (charts.video_url)
--
-- ─── 왜 ──────────────────────────────────────────────────
-- 서열표는 "이 채보가 얼마나 어려운가" 를 투표로 정하는 표인데, 정작 그 채보가
-- 어떻게 생겼는지는 화면 어디에도 없었습니다. 처음 보는 채보에 투표하려면
-- 유튜브를 따로 찾아야 했습니다.
--
-- ─── 왜 표를 따로 만들지 않았나 ───────────────────────────
-- 한 채보에 영상은 하나면 충분합니다(대표 플레이 영상 하나). 1:N 이 될 때 —
-- 난이도별·플레이어별 영상을 여러 개 걸 때 — 그때 chart_videos 로 옮기면 됩니다.
-- 지금 표를 하나 더 만들면 조회마다 조인이 하나 더 붙습니다.
--
-- ─── 주소는 유튜브만 ──────────────────────────────────────
-- 값 자체는 TEXT 지만 **화면이 youtube.com · youtu.be 만 링크로 그립니다**
-- (lib/tier-types.ts youtubeWatchUrl). DB 에 들어온 값을 그대로 href 에 넣으면
-- javascript: 같은 주소가 링크가 됩니다 — 판정은 화면에서 한 번 더 합니다.
--
-- ⚠ 여러 번 실행해도 결과가 같아야 합니다 (lib/db.ts runMigrations 주석 참고).
-- ============================================================

ALTER TABLE charts ADD COLUMN IF NOT EXISTS video_url TEXT;

COMMENT ON COLUMN charts.video_url IS
  '이 채보의 대표 플레이 영상(유튜브). NULL 이면 상세에 링크가 뜨지 않는다.';

-- ─── 첫 영상 한 건 ────────────────────────────────────────
-- 값을 여기 적는 이유: dev DB 에서 UPDATE 로만 넣으면 저장소에는 남지 않아
-- 다른 사람이 받은 DB 에는 영영 비어 있습니다 (2026-08 에 050~057 로 겪은 일).
--
-- id 가 아니라 **게임·곡·모드·레벨**로 찾습니다 — charts.id 는 DB 마다 다릅니다.
-- 이미 값이 있으면 건드리지 않습니다: 나중에 손으로 바꾼 주소를 마이그레이션
-- 재실행이 되돌리면 안 됩니다.
--
-- 고른 기준: **직캠이 아니라 채보 화면**입니다. 발판을 밟는 사람을 찍은 영상은
-- 이 칸의 쓸모(투표 전에 채보가 어떻게 생겼는지 보는 것)에 맞지 않습니다.
-- 이 영상은 S4 와 S7 을 나란히 보여 줍니다 — 왼쪽이 S4. S4 단독 채보 영상은
-- 찾지 못했습니다 (2026-09-16 기준).
UPDATE charts c
   SET video_url = 'https://www.youtube.com/watch?v=Tp3VOfq4Lx0'
  FROM songs s
  JOIN machines m ON m.id = s.machine_id
 WHERE s.id = c.song_id
   AND m.name = 'Pump It Up'
   AND s.title = 'Beethoven Virus'
   AND c.mode = 'S'
   AND c.level = 4
   AND c.video_url IS NULL;
