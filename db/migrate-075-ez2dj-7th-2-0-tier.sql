-- ─── 곡 이름이 두 줄인 곡 둘 ─────────────────────────────
-- 표에 같은 이름이 두 줄인 곡이 둘 있습니다. 059 가 그랬듯 **같은 곡의 채보 하나
-- 더**로 넣습니다 — 곡을 쪼개면 (machine_id, title) UNIQUE 에 걸리고, 레벨이 달라
-- 채보 쪽 열쇠에는 걸리지 않습니다.
--
--   Lucid            Turn 10 과 **Turn 13**
--   Theme of EZ2DJ 2 Catch 9 와 **Catch 12**
