-- ─── ⚠ 16레벨을 그대로 둡니다 (074 와 반대) ──────────────
-- 표 전체에서 16 은 둘입니다 — Hyper Magic 의 Space NM, Lucid 의 Club HD.
-- 074 는 이 둘을 `Lv.?` 로 돌렸습니다. **1.5 표가 아니라 2.01 표에서 빌려 온
-- 값이었기 때문**입니다. 여기서는 그 표가 곧 이 버전의 표라 16 이 제 값입니다.
