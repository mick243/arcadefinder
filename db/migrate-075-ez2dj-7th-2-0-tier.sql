-- ─── 074 와 달리 표를 통째로 싣습니다 ────────────────────
-- 074(1.5)는 1.0 채보를 **복사한 뒤 더한 것만 얹었습니다**. 1.5 전용 난이도표가
-- 없어서 그럴 수밖에 없었습니다. 2.0 은 반대입니다 — 완전한 표가 있으므로 060 처럼
-- **표 하나를 그대로** 싣습니다. 델타로 쌓으면 안 되는 이유는 2.0 이 신곡만 더한
-- 것이 아니라 **구곡 난이도를 대거 손봤기** 때문입니다. 세 예:
--
--   Get the beat   5Street HD  10 → 7    (1.0 값이 그대로 남을 뻔했습니다)
--   Quake in Kyoto 7Street NM   6 → 5, HD 11 신설, 5Street HD 10 → 11
--   Metagalactic   5Street SHD 13 → 14   (1.5 문서가 "2.0 패치부터 14" 라고 적은 것)
--
-- 그래서 이 파일은 1.5 버전의 채보를 **참조하지 않습니다.** 두 버전은 서로
-- 독립이고, 화면의 버전 선택기가 가릅니다.
--
-- ─── 표가 가로로 16칸입니다 ──────────────────────────────
--   Ruby N·H │ 5Street E·N·H·S │ 7Street E·N·H·S │ Club N·H │ Space N·H │ Catch │ Turn
--
-- 1.0/1.5 의 14칸에서 **Ruby HD** 와 **7Street SHD** 가 늘었습니다. 074 가
-- "2.0 에서 생긴 칸" 이라며 잘라냈던 바로 그 둘인데, 여기서는 제자리를 찾습니다.
-- 아래 3) 의 컬럼 차례가 문서의 가로 차례 그대로라 한 줄씩 대조할 수 있습니다.
-- `-` 는 그 채보가 없다는 뜻, 숫자가 난이도입니다.
--
-- ─── 1.5 의 곡은 하나도 빠지지 않았습니다 ────────────────
-- 2.0 표의 곡 이름을 1.5 서열표의 181곡과 대조하니 **7곡이 안 붙었는데**, 전부
-- 2.0 이 이름을 바꿔 적은 것이었습니다. 난이도 값이 1.5 것과 겹치는 칸에서 모두
-- 같아 같은 곡으로 판정했고, 아래 2) 의 별칭표에 `값으로 확인` 으로 표시했습니다.
--
--   Look out ~Here comes my love~ = Look Out        (RUBY1 5E1 5N3 5H5 7N5 CLUB7 CATCH5)
--   Confete (Evening Mix)         = Confete ~ Remix ~  (RUBY5 5N4 7N4 CLUB4 · 1.0 은 Confete (Remix))
--   Judgement                     = Judgment        (RUBY3 5N4 5H6 7N6 CLUB7 SPACE7)
--   One Two Three Four            = 1234            (RUBY3 5N5 5H8 5S9 7N5 CLUB6 CATCH7 TURN5)
--   Theme of EZ2DJ 2              = Ez2Dj (찬가 II)  (RUBY3 5N5 5H7 7N5 CLUB6 SPACE7 CATCH9 TURN5)
--   Be My Baby (Funky Ver.)       = Be My Baby Funky Mix      (RUBY3 5N5 7N5 CLUB5 SPACE5)
--   With U Girl (Beach Ver.)      = With you Girl Beach Ver.  (RUBY4 5N6 5H7 7N5)
--
-- 나머지 44줄은 대소문자 · 구두점만 다른 것들입니다 (060 과 같은 기준 — 영숫자만
-- 남기고 소문자로 내렸을 때 같은 것). 결과: 표의 192곡 중 **181곡이 이미 있는 곡**
-- 이고 **11곡이 새로** 들어갑니다.
--
-- ─── ⚠ 신곡 12곡 중 6곡만 들어갑니다 ─────────────────────
-- 2.0 문서가 신곡으로 세는 것은 12곡인데, 수록곡 표에 칸이 있는 것은 여섯뿐입니다.
--
--   들어가는 것 6 — Don't Say Anything · One's Trash · SINUS · weep Irish -RE- ·
--                   Frantic (YK Edit) · One Two Three Four (SJ Remix)
--   빠지는 것  6 — 2nd Life · Aura · R-decision
--                     └ 문서 각주: "5/7키 라디오 Musician's Collection, SJHdeux
--                       채널에서만 등장". 라디오 채널 전용이라 (모드, 레벨)이 없습니다.
--                   Dance Machine (YK House Edit) · Dance With Me (Dischord Edit) ·
--                   Refresh (J-Style Edit)
--                     └ 문서 본문: yak_won 리믹스는 "원곡의 하드믹스 형태로 수록".
--                       즉 이 채보들은 **원곡 줄의 HD 칸에 이미 들어 있습니다**
--                       (Dance Machine 5Street HD 10 등). 곡을 따로 만들면 같은
--                       채보가 두 번 서게 됩니다.
--
-- 서열표는 (모드, 레벨) 칸에 채보를 놓는 표라, 그 둘이 없는 곡은 놓을 자리가
-- 없습니다. 빈 곡 행만 만들면 어느 화면에도 안 나오면서 곡 수만 부풀립니다.
--
-- ─── 부활곡 4곡과 Lucid (Another) ────────────────────────
-- 새로 들어오는 11곡이 전부 신곡인 것은 아닙니다. 2.0 은 1st · SE 시절 곡을
-- 되살렸고(문서 5.1 「부활곡」), 그 넷이 표에 줄을 갖습니다 — Do you remember? ·
-- Freedom · Mystic Dream 9903 · Quake in Kyoto (Mega Mix). 여기에 표가 따로 줄을
-- 준 Lucid (Another) 를 더해 11곡입니다.
--
-- ⚠ `Do you remember?` 는 `Do you remember ? ~ Remix ~` 와 **다른 곡**입니다
--   (원곡이 돌아온 것). 표에도 두 줄이 따로 있고 값이 겹치지 않습니다.
--   `Mystic Dream 9903` 과 `Mystic Dream 9903 ~ Horror mix ~` 도 마찬가지입니다.
