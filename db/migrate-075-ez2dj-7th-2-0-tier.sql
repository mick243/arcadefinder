-- ─── 4) 곡 (새로 들어오는 11곡만 늘어납니다) ──────────────
INSERT INTO songs (machine_id, title, artist)
SELECT DISTINCT 10, COALESCE(a.canon, t.title), NULL
FROM ez2dj_20 t
LEFT JOIN ez2dj_20_alias a ON a.wiki = t.title
ON CONFLICT DO NOTHING;

-- ─── 5) 채보 1,549개 ──────────────────────────────────────
-- 가로 16칸을 세로로 펼칩니다. `-` 는 채보가 없다는 뜻이라 버리고, `?` 는 난이도만
-- 모르는 것이라 레벨을 NULL 로 남깁니다.
CREATE TEMP TABLE ez2dj_20_charts AS
SELECT COALESCE(a.canon, t.title) AS title,
       v.mode,
       v.difficulty,
       CASE WHEN v.val = '?' THEN NULL ELSE v.val::int END AS level
FROM ez2dj_20 t
LEFT JOIN ez2dj_20_alias a ON a.wiki = t.title
CROSS JOIN LATERAL (VALUES
  ('RUBY',  'NM',  t.ruby_n),
  ('RUBY',  'HD',  t.ruby_h),
  ('5ST',   'EZ',  t.s5e),
  ('5ST',   'NM',  t.s5n),
  ('5ST',   'HD',  t.s5h),
  ('5ST',   'SHD', t.s5s),
  ('7ST',   'EZ',  t.s7e),
  ('7ST',   'NM',  t.s7n),
  ('7ST',   'HD',  t.s7h),
  ('7ST',   'SHD', t.s7s),
  ('CLUB',  'NM',  t.club_n),
  ('CLUB',  'HD',  t.club_h),
  ('SPACE', 'NM',  t.sp_n),
  ('SPACE', 'HD',  t.sp_h),
  ('CATCH', 'NM',  t.cat_n),
  ('TURN',  'NM',  t.turn_n)
) AS v(mode, difficulty, val)
WHERE v.val NOT IN ('X', '-', '');

-- 컬럼 목록을 DB 상태에 맞춰 짭니다 — 059 머리말의 `level_label` 항목 참고.
DO $mig$
DECLARE
  has_label BOOLEAN := EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'charts' AND column_name = 'level_label'
  );
BEGIN
  EXECUTE format($q$
    INSERT INTO charts (song_id, version_id, mode, difficulty, level%s)
    SELECT s.id, gv.id, e.mode, e.difficulty, e.level%s
    FROM ez2dj_20_charts e
    JOIN songs s          ON s.machine_id  = 10 AND s.title = e.title
    JOIN game_versions gv ON gv.machine_id = 10 AND gv.code = '7th2.0'
    ON CONFLICT DO NOTHING
  $q$,
    CASE WHEN has_label THEN ', level_label'                    ELSE '' END,
    CASE WHEN has_label THEN ', COALESCE(e.level::text, ''?'')' ELSE '' END);
END
$mig$;

DROP TABLE ez2dj_20_charts;
