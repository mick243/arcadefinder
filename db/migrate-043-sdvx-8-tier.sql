-- ============================================================
-- 043 · 사볼 서열표를 5단 → 8단으로 (S · A+ · A · B · C · D · E · F)
--
-- ─── 왜 ──────────────────────────────────────────────────
-- 5단(최상·상·중·하·최하)은 해상도가 부족했습니다. SDVX 커뮤니티 난이도표
-- (18~20LV, 336곡)의 실제 투표 분포를 이 프로젝트 집계 규칙에 넣어 보면
-- **'중' 한 등급에 134곡(39.9%)** 이 몰립니다. 원본 표에서 각각 77곡·74곡으로
-- 가장 두꺼운 두 등급(B·C)이 하나로 뭉개지기 때문입니다. 양 끝(최상 3.6%,
-- 최하 1.8%)은 거의 비어서, 5단 중 실질적으로 쓰이는 것은 상·중·하 3칸이었습니다.
--
-- 그래서 커뮤니티 표와 같은 8단으로 올립니다. 펌프(7단)와 단계 수가 다른 것은
-- 의도된 것입니다 — 게임마다 등급 수를 다르게 둘 수 있는 구조입니다.
--
-- ─── anchor 와 그 결과 띠 ────────────────────────────────
-- 등급은 "평균에 가장 가까운 anchor" 로 정해지고, 동점이면 0 에 가까운 안쪽
-- 등급이 이깁니다(migrate-035). 그래서 실제 띠는 인접 anchor 의 중점이 경계입니다.
--
--   S    +1.00   (+0.85 ~ +1.00]   폭 0.15
--   A+   +0.70   (+0.60 ~ +0.85]   폭 0.25
--   A    +0.50   (+0.35 ~ +0.60]   폭 0.25
--   B    +0.20   (+0.05 ~ +0.35]   폭 0.30
--   C    -0.10   [-0.25 ~ +0.05]   폭 0.30
--   D    -0.40   [-0.55 ~ -0.25)   폭 0.30
--   E    -0.70   [-0.85 ~ -0.55)   폭 0.30
--   F    -1.00   [-1.00 ~ -0.85)   폭 0.15
--
-- 합이 정확히 2.00 으로 투표 범위(-1.00 ~ +1.00)를 빈틈없이 덮습니다.
-- 위쪽(S·A+)이 촘촘하고 가운데(B·C·D·E)가 균등한 배치입니다 — 상위 등급은
-- 촘촘해야 구분이 되고, 양 끝은 원래 곡이 적습니다.
--
-- ─── code 는 CSS 클래스가 된다 ───────────────────────────
-- `code` 는 화면에서 `tier-${code}` 클래스로 쓰입니다
-- (TierBoardView.tsx · ChartDetailPanel.tsx). 그래서 'A+' 를 code 로 쓸 수
-- 없습니다 — `.tier-A+` 는 '+' 가 CSS 결합자라 선택자가 깨집니다.
-- 표기는 label 에 두고 code 는 안전한 소문자로 둡니다 ('ap' = A+).
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- machine_id=3 의 등급을 지우고 다시 넣습니다. tier_grades 를 가리키는 FK 는
-- 없고(charts.tier_code 는 그냥 TEXT), 마지막에 전체를 재계산하므로 옛 코드가
-- 남지 않습니다.
--
-- 되돌리려면 이 파일의 INSERT 를 5단(migrate-014 의 값)으로 바꿔 다시 돌리고
-- recalc_chart_stats(NULL) 을 부르세요.
-- ============================================================

-- 5단 → 8단이라 sort_order 가 겹칩니다. UNIQUE(machine_id, sort_order) 때문에
-- 갱신이 아니라 지우고 넣습니다.
