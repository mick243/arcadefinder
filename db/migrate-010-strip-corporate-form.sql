-- ============================================================
-- 오락실 이름에서 법인 형태 표기 빼기
--
-- 공공데이터포털 인허가 데이터는 간판 이름이 아니라 **사업자명**을 적습니다.
-- 그래서 이렇게 들어와 있습니다:
--
--   (주)대빵오락실 방이점
--   주식회사 대빵오락실 사상점
--   금호리조트(주) 설악오락실
--   리얼엔젤플러스(주)블루스톤 스포츠 내 게임장
--
-- 사용자에게 보여줄 이름은 '대빵오락실 방이점' 이므로 법인 표기를 뺍니다.
-- 네이버 지역 검색으로 넣은 행에는 이런 표기가 없습니다(간판 이름을 주므로).
--
-- ⚠ 지우는 자리에 **빈칸을 넣습니다.** 그냥 지우면
--   '리얼엔젤플러스(주)블루스톤' 이 '리얼엔젤플러스블루스톤' 으로 붙습니다.
--   빈칸으로 바꾼 뒤 연속 공백을 하나로 줄이고 앞뒤를 다듬습니다.
--
-- ⚠ 이름이 통째로 사라지는 경우(예: name 이 '(주)' 뿐)는 건드리지 않습니다.
--   name 은 NOT NULL 이고, 이름 없는 행보다 법인 표기가 남은 행이 낫습니다.
--
-- ⚠ 여러 번 실행해도 결과가 같아야 합니다 (lib/db.ts runMigrations 주석 참고).
--   이미 뺀 이름에는 패턴이 없으므로 WHERE 에 걸리지 않습니다.
--
-- 앞으로 들어올 행은 scripts/import-localdata-arcades.ts 가 넣기 전에
-- lib/localdata-games.ts 의 stripCorporateForm 으로 같은 처리를 합니다.
-- 규칙을 바꿀 때는 **양쪽을 같이** 고쳐야 합니다.
-- ============================================================

UPDATE arcades
   SET name = regexp_replace(
                regexp_replace(name, '\(주\)|（주）|㈜|주식회사', ' ', 'g'),
                '\s+', ' ', 'g'
              ),
       updated_at = now()
 WHERE name ~ '\(주\)|（주）|㈜|주식회사'
   -- 다듬은 결과가 빈 문자열이 되는 행은 제외합니다.
   AND btrim(regexp_replace(regexp_replace(name, '\(주\)|（주）|㈜|주식회사', ' ', 'g'),
                            '\s+', ' ', 'g')) <> '';

-- 위 UPDATE 는 앞뒤 공백을 남깁니다('(주)대빵오락실' → ' 대빵오락실').
-- btrim 을 UPDATE 안에서 하면 WHERE 조건과 식이 길어져 읽기 어려워지므로 나눕니다.
UPDATE arcades
   SET name = btrim(name)
 WHERE name <> btrim(name);
