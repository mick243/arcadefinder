-- ============================================================
-- 아이디/비밀번호로 가입한 사람의 이메일
--
-- 지금까지 가입은 아이디와 비밀번호만 받았습니다. 쓸 데가 없으면 이메일은
-- "지키기만 해야 하는 개인정보" 라서 받지 않는 쪽이 맞았습니다. 이제 받는
-- 이유는 **비밀번호를 잊은 사람에게 돌려줄 길**과 **본인 확인 메일**이
-- 이메일 없이는 아예 만들 수 없기 때문입니다 (SSOT R7).
--
--   NULL 을 허용합니다. 채울 수 없는 줄이 이미 셋입니다 —
--     · 소셜로만 가입한 사람 (이메일은 player_identities 에 있습니다, 아래)
--     · 환경변수로 만들어지는 관리자 (lib/auth.ts ensureAdminAccount)
--     · 이 마이그레이션 이전에 가입한 사람
--   NOT NULL 로 두면 이들에게 가짜 값을 채워 넣어야 하고, 그 순간
--   "이메일이 있다" 가 아무 뜻도 없는 칸이 됩니다.
--
--   lower(email) 에 UNIQUE 를 겁니다. 비밀번호 찾기는 이메일 하나로 사람을
--   **특정**할 수 있어야 성립합니다 — 같은 주소를 쓰는 계정이 둘이면 어느
--   쪽으로 보낼지 정할 수 없습니다. lower() 인 이유는 닉네임과 같습니다
--   (migrate-027): 겉보기가 같은 주소가 둘 생기면 안 됩니다. 입력 경계에서도
--   소문자로 맞춰 넣지만(lib/validation.ts emailField), 그 경계를 거치지 않고
--   들어오는 줄에 대비해 인덱스로도 막습니다.
--   NULL 은 서로 다른 값으로 취급되므로 위 세 부류는 얼마든지 공존합니다.
--
-- ⚠ player_identities.email 을 여기로 복사하지 않습니다.
--   migrate-008 이 정한 것 — 이메일로 계정을 합치지 않습니다(제공자마다 검증
--   여부가 달라, 검증 안 된 주소로 합치면 남의 계정을 가져갈 길이 열립니다).
--   복사하면 그 결정이 무너집니다: 같은 사람이 구글과 카카오로 각각 만든 두
--   계정이 같은 주소를 갖게 되어 위 UNIQUE 에 부딪힙니다. 소셜 쪽 이메일은
--   지금처럼 player_identities 에 참고용 사본으로 남습니다.
--
-- ⚠ 이 칸의 주소는 **아직 확인되지 않은 주소**입니다. 인증 메일을 붙일 때
--   email_verified_at 과 토큰 표가 따라옵니다 — 그 전까지는 "가입할 때 적어 낸
--   주소" 이상으로 믿으면 안 됩니다.
--
-- ⚠ 여러 번 실행해도 안전해야 합니다 (lib/db.ts runMigrations 주석 참고).
-- ============================================================

ALTER TABLE players ADD COLUMN IF NOT EXISTS email TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS players_email_lower_idx
  ON players (lower(email));
