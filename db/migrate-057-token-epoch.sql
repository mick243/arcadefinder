-- 세션 회수 — players.token_epoch
--
-- 세션 쿠키는 저장소 없이 **서명만으로** 성립합니다 (lib/auth.ts sealPayload).
-- 값이 서버에 남지 않으니 "이 쿠키는 이제 무효" 라고 말할 자리도 없었습니다 —
-- 비밀번호를 바꿔도 이미 나간 쿠키가 7일을 살았고, 그게 세션을 뺏긴 사람이
-- 스스로 할 수 있는 일이 없다는 뜻이었습니다 (docs/QA-LAUNCH-READINESS.md H12).
--
-- 세션 테이블을 만드는 대신 계정마다 **세대 번호** 하나를 둡니다. 토큰에 발급
-- 당시의 번호를 함께 봉하고 요청마다 지금 번호와 맞는지 봅니다. 번호를 1 올리면
-- 그 계정의 지난 쿠키가 한꺼번에 무효가 됩니다 — 줄 하나 UPDATE 로.
--
-- 세션 테이블이었다면 기기 목록·마지막 접속 같은 걸 보여 줄 수 있지만, 만료된
-- 줄을 치우는 일이 따라옵니다. 지금 필요한 건 "전부 끊기" 하나뿐입니다.
ALTER TABLE players ADD COLUMN IF NOT EXISTS token_epoch INTEGER NOT NULL DEFAULT 0;
