-- ============================================================
-- 036 · 채보 성향 태그 교체 (물렙·불렙·개인차·기습 → 저속·기믹·체중이동·연타)
--
-- ─── 무엇이 바뀌나 ───────────────────────────────────────
-- 화이트리스트(lib/community-types.ts CHART_TAGS)에서 4개를 빼고 4개를 넣습니다.
-- 태그 총 개수는 12개 그대로입니다.
--
--   빠짐: 물렙 · 불렙 · 개인차 · 기습
--   들어감: 저속 · 기믹 · 체중이동 · 연타
--
-- 목록 자체는 코드에 있으므로(집계용 고정 목록이라 DB 테이블이 아닙니다)
-- 이 파일이 하는 일은 **이미 저장된 평가에서 빠진 태그를 지우는 것**뿐입니다.
--
-- ─── 왜 지워야 하나 ──────────────────────────────────────
-- 읽기 경로는 태그를 검증하지 않으니 그냥 두면 화면에는 계속 보입니다. 문제는
-- 쓰기입니다 — 평가 폼은 기존 태그를 그대로 불러오고(ChartComments.tsx
-- setTags(mine?.tags)) 저장 시 zod 가 화이트리스트로 검증하므로
-- (lib/validation.ts z.enum(CHART_TAGS)), 빠진 태그가 남아 있으면 **그 평가를
-- 쓴 사람이 자기 글을 수정할 수 없습니다.** 화면에 칩도 안 켜지니 원인도 안 보입니다.
--
-- ─── 지우기만 하고 갈아끼우지 않습니다 ───────────────────
-- 빠진 4개는 새 4개와 뜻이 겹치지 않습니다 (기습 ≠ 기믹). 임의로 대응시키면
-- 남이 쓴 평가의 내용을 바꾸는 셈이라 지우기만 합니다. 본문은 건드리지 않으므로
-- "물렙 소리 나올 만합니다" 같은 문장은 그대로 남습니다.
--
-- ⚠ **updated_at 은 올리지 않습니다.** 목록이 timeAgo(updatedAt) 를 보여주므로
--   올리면 작성자가 방금 고친 것처럼 보입니다. 태그 정리는 작성자의 수정이 아닙니다.
--
-- ⚠ 서열표의 '개인차' 등급(tier_code = 'unique')과는 무관합니다 — 이름만 같고
--   그쪽은 수렴도로 자동 판정되는 등급이라 그대로 둡니다.
--
-- ─── 대상 ────────────────────────────────────────────────
-- 적용 시점의 seed-community.sql 가상 평가 5건 (개인차 3 · 물렙 2 · 기습 1 · 불렙 1).
-- 시드는 그때 상태로 두고 고치는 것은 마이그레이션이 합니다 — 새로 만든 DB 도
-- 시드가 넣은 뒤 이 파일이 정리합니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- 두 번째 실행에는 걸리는 행이 없습니다 (WHERE tags && …).
--
-- 되돌릴 수 없습니다 — 지운 태그는 복구되지 않습니다. 목록만 되돌리려면
-- CHART_TAGS 에 4개를 다시 넣으면 됩니다.
-- ============================================================

UPDATE chart_comments SET
  tags = ARRAY(
    SELECT t FROM unnest(tags) AS t
    WHERE t <> ALL (ARRAY['물렙', '불렙', '개인차', '기습'])
  )
WHERE tags && ARRAY['물렙', '불렙', '개인차', '기습'];
