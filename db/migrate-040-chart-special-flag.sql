-- ============================================================
-- 040 · 특수 패턴 표시 (charts.is_special) + 서열표 '특수패턴' 칸
--
-- ─── 무엇을 만드는가 ─────────────────────────────────────
-- 기믹·연출로 난이도가 정해지는 채보를 체감 난이도 줄 세우기에서 빼내는 표시입니다.
-- 채보 상세의 체크박스(채보 평가 위)로 켜면 서열표에서 **개인차 아래 '특수패턴'
-- 칸**으로 옮겨집니다 (lib/tier.ts SPECIAL_CODE · getTierBoard).
--
-- ─── 왜 컬럼 하나인가 ────────────────────────────────────
-- 투표(difficulty_votes)처럼 사람마다 받지 않습니다. "이 채보에 기믹이 있는가" 는
-- 갈리는 평가가 아니라 채보의 성질이라 합산할 것이 없습니다. 그래서 채보당 값
-- 하나이고, 클리어 게이트도 없습니다 (평가란과 같은 이유 — 못 깨도 보입니다).
--
-- ─── ⚠ tier_code 를 덮지 않습니다 ────────────────────────
-- 집계 함수(recalc_chart_stats)는 이 컬럼을 읽지도 쓰지도 않습니다. 등급은 원래
-- 계산대로 tier_code 에 남고, 서열표가 **읽을 때만** 특수패턴 칸으로 보냅니다.
--   · 표시를 끄면 원래 등급이 즉시 돌아옵니다 (재계산 필요 없음)
--   · 표시된 채보의 투표도 그대로 살아 있습니다
-- 상태를 두 곳에 쓰지 않으려는 선택입니다 — tier_code 에 'special' 을 써 버리면
-- 끌 때 무슨 등급이었는지 알 수 없어 재계산이 필요해집니다.
--
-- ─── 기본값 ──────────────────────────────────────────────
-- 전부 FALSE 로 시작합니다. 어느 채보가 특수 패턴인지는 사람이 표시해야 하는
-- 판단이라, 자동으로 켜 줄 근거가 없습니다 (기믹 여부를 담은 데이터가 없습니다).
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- ADD COLUMN IF NOT EXISTS.
--
-- 되돌리려면: ALTER TABLE charts DROP COLUMN is_special;
--   (코드에서 SPECIAL_CODE 그룹과 체크박스도 함께 빼야 합니다)
-- ============================================================

ALTER TABLE charts
  ADD COLUMN IF NOT EXISTS is_special BOOLEAN NOT NULL DEFAULT FALSE;
