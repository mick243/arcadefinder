-- 047 이 넣은 Lv17 서열표(SDVX17LV初クリア難易度表, 681곡)에 **없는** Lv17 채보
-- 4개입니다. 넷 다 seed-community.sql 이 만든 시드 데이터입니다.
--
--   Bangin' Burst        [EXH]  투표 7 · 등급 A+
--   FLOWER               [EXH]  투표 6 · 등급 E   · 코멘트 1
--   ちくわパフェだよ☆CKP [EXH]  투표 7 · 등급 개인차 · 코멘트 1
--   ドーナツホール       [EXH]  투표 4 · 등급 E
--
-- 곡(songs)까지 지웁니다. 넷 다 이 Lv17 채보가 유일한 채보여서, 채보만 지우면
-- 채보 없는 곡 행이 남습니다 (지금 사볼에는 그런 행이 하나도 없습니다).
--
-- ⚠ **투표 24건 · 클리어 24건 · 코멘트 2건이 함께 사라집니다.**
--   songs → charts → clear_records → difficulty_votes 가 전부 ON DELETE CASCADE 이고
--   chart_comments 도 charts 에서 CASCADE 입니다. 시드로 만든 가상 데이터라
--   실제 사용자 기록은 아닙니다.
--
-- ⚠ **이 4개가 Lv17 서열표에서 등급이 매겨진 유일한 채보였습니다.** 지운 뒤
--   Lv17 은 681곡 전부 '미정' 이 됩니다 (047 이 투표를 넣지 않으므로).
--   `Verse IV [EXH]` 는 시트(B+ 밴드)에 있어 남고, 투표 5건과 등급 C 도 그대로입니다.
--
-- ─── ⚠ Lv18 은 건드리지 않습니다 ─────────────────────────
-- 사볼 Lv18 시드 채보 10개도 "시트에 없다" 로 걸리지만, 047 이 읽은 시트는
-- **Lv17 표**입니다. Lv17 표에 Lv18 채보가 없는 것은 당연한 일이라 근거가
-- 되지 못합니다. Lv18 을 정리하려면 그 레벨의 표를 따로 넣어야 합니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- 이미 지워졌으면 0행이 지워집니다.
--
-- ⚠ 되돌릴 수 없습니다 — 지워진 투표·클리어·코멘트는 복구되지 않습니다.
--   곡과 채보만 되살리려면 seed-community.sql 의 해당 INSERT 를 다시 돌리세요
--   (투표는 그 파일이 만드는 값이라 같은 분포로 다시 생깁니다).
-- ============================================================

DELETE FROM songs s
WHERE s.machine_id = 3
  AND s.title IN ('Bangin'' Burst', 'FLOWER', 'ちくわパフェだよ☆CKP', 'ドーナツホール')
  -- 시트에 있는 같은 제목을 실수로 지우지 않도록, 이 곡의 채보가 Lv17 하나뿐인
  -- 경우로 한정합니다. 넷 다 여기에 해당합니다.
  AND (SELECT count(*) FROM charts c WHERE c.song_id = s.id) <= 1
  AND NOT EXISTS (
        SELECT 1 FROM charts c WHERE c.song_id = s.id AND c.level <> 17
      );
