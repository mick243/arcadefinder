-- ============================================================
-- 060 · EZ2DJ 7th TRAX ~Resistance~ 서열표 (채보만 · 투표 없음)
--
-- ─── 무엇을 만드는가 ─────────────────────────────────────
-- EZ2DJ 의 두 번째 버전입니다. 곡 170개 · 채보 **1,080개**. 059 와 같은 기준으로
-- **투표는 넣지 않아** 전부 '미정' 에서 시작합니다.
--
-- ─── 출처 ────────────────────────────────────────────────
--   나무위키 『EZ2DJ 7th TRAX ~Resistance~/수록곡』 2장 목록
--   https://namu.wiki/w/EZ2DJ 7th TRAX ~Resistance~/수록곡
--
-- 표가 가로로 14칸입니다 — 059(6th)의 9칸에서 난이도가 둘 늘고 모드마다 갈립니다.
--
--   Ruby │ 5Street E·N·H·S │ 7Street E·N·H │ Club N·H │ Space N·H │ Catch │ Turn
--
-- 아래 임시 표의 컬럼 차례가 그 차례 그대로라 한 줄씩 대조할 수 있습니다.
-- `-` 는 그 채보가 없다는 뜻이고, 숫자가 난이도입니다(1~15).
--
-- ─── 난이도가 둘 늘어 자리를 다시 잡습니다 ───────────────
-- 059 는 NM·HD 둘이었는데 7th 에는 **EZ**(5Street·7Street)와 **SHD**(5Street)가 더
-- 있습니다. 쉬운 순서가 EZ → NM → HD → SHD 라 sort_order 를 다시 매겨야 하는데,
-- `UNIQUE (machine_id, sort_order)` 때문에 UPDATE 로 밀면 중간에 충돌합니다.
-- 그래서 기종 것만 지우고 넷을 다시 넣습니다 — charts.difficulty 는 코드(문자열)로
-- 가리키므로 FK 가 없고, 6th 채보의 'NM'·'HD' 는 그대로 유효합니다.
--
-- ⚠ 표는 한 글자(E·N·H·S)로 적지만 코드는 EZ2 시리즈 관례인 EZ · NM · HD · SHD 를
--   씁니다. 059 도 같은 이름을 쓰고, 임시 표의 컬럼 이름만 원문 글자를 따릅니다.
--
-- ─── ⚠ 곡 이름이 6th 페이지와 다릅니다 ───────────────────
-- 같은 곡을 두 문서가 다르게 적습니다. 그대로 넣으면 **같은 곡이 songs 에 두 줄**이
-- 됩니다 (`Dieoxin` 과 `DIEOXIN`, `1234` 와 `One Two Three Four`).
-- 그래서 아래 4) 에 **별칭 표 50줄**을 두고 이미 있는 이름으로 붙입니다.
--
--   44줄 — 대소문자·구두점만 다름. 영숫자만 남기고 소문자로 내렸을 때 같은 것만
--          골랐습니다 (`Back For More` = `Back for more`).
--   6줄  — 글자로는 못 잇고 **난이도 값이 전부 같아서** 같은 곡으로 판정한 것들.
--          6th 채보와 공통 칸을 대조해 확인했습니다.
--            Judgement            = Judgment              (RUBY3 5N4 5H6 7N6 CLUB7 SPACE7)
--            One Two Three Four   = 1234                  (RUBY3 5N5 5H8 7N5 CLUB6 SPACE6 CATCH7 TURN5)
--            Theme of EZ2DJ 2     = Ez2Dj (찬가 II)        (RUBY3 5N5 5H7 7N5 CLUB6 SPACE7 CATCH9 TURN5)
--            Stay (Remix)         = Stay ~ Radio Edit ~   (SPACE7 하나뿐인 것까지 같음)
--            Be My Baby (Funky Ver.) = Be My Baby Funky Mix  (RUBY3 5N5 7N5 CLUB5 SPACE5)
--            With U Girl (Beach Ver.) = With you Girl Beach Ver. (RUBY4 5N6 5H7 7N5 CLUB6)
--
-- 결과: 7th 의 170곡 중 **138곡이 이미 있는 곡**(그대로 88 + 별칭 50)이고 **32곡이
-- 새로** 들어갑니다. EZ2DJ 곡은 138 → 170 이 됩니다.
--
-- ⚠ 별칭은 **7th 쪽 이름을 버리는 것**입니다. 화면에는 6th 때 넣은 이름으로 보입니다.
--   어느 쪽 표기를 정본으로 삼을지는 나중에 한 번에 정리하는 편이 낫습니다.
--
-- ─── ⚠ 옮기지 못한 칸 ────────────────────────────────────
--   `?` 3개 — G.O.A · Legacy of Hatred (live) · Revelation 의 **Space N**.
--             059 와 같이 `charts.level` 을 NULL 로 넣어 `Lv.?` 칸에 모읍니다.
--   `0` 1개 — DIEOXIN 의 **Turn**. 이 게임에 0레벨은 없습니다(1~15). 문서 쪽 오타로
--             보이는데 무엇이었는지 알 수 없어 **넣지 않습니다.** 추측해 채우면
--             없는 난이도를 지어내는 것이고, `?` 로 돌리면 문서가 모른다고 적은 것과
--             편집 실수를 같은 칸에 섞게 됩니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- 행은 전부 ON CONFLICT DO NOTHING, 난이도는 지우고 다시 넣기.
-- `level_label` 이 있는 DB 에서도 도는 이유는 059 머리말과 같습니다.
