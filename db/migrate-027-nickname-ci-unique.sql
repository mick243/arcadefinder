-- ============================================================
-- 닉네임 겉보기 중복 차단
--
-- players.nickname 의 UNIQUE 는 바이트가 같아야만 걸립니다. 그래서
-- 'Player' 와 'player' 처럼 **대소문자만 다른 이름**이 둘 다 들어올 수 있고,
-- 목록에서는 사실상 같은 사람으로 보입니다 — 제보·리뷰·글의 작성자를
-- 이름으로 알아보는 앱에서는 이게 곧 사칭 통로입니다.
--
-- lower() 함수 인덱스로 막습니다. 한글 이름에는 아무 영향이 없고(lower 가
-- 그대로 돌려줌), 영문이 섞인 이름만 대소문자 무시로 좁아집니다.
--
-- 유니코드 조합형/완성형(NFC/NFD) 차이는 여기서 잡지 않습니다 — 인덱스 식에
-- normalize() 를 넣는 대신, 입력 경계(lib/validation.ts nicknameField)가
-- 저장 전에 NFC 로 맞춰 넣습니다. 이 마이그레이션 시점의 기존 15명은 전부
-- NFC 였음을 확인했습니다 (2026-08-24).
--
-- ⚠ 여러 번 실행해도 안전해야 합니다 (lib/db.ts runMigrations 주석 참고).
-- ============================================================

CREATE UNIQUE INDEX IF NOT EXISTS players_nickname_lower_idx
  ON players (lower(nickname));
