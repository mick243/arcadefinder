-- ============================================================
-- 014 · Pump It Up 등급 스케일 재조정 + 가상 투표 정리
--
-- 네 가지를 바꿉니다. 모두 machine_id = 1 (Pump It Up) 범위입니다 —
-- 등급표와 임계값은 기종별이고, SOUND VOLTEX(machine_id = 3)는 5단계 · 자기
-- 임계값을 따로 갖습니다 (seed-community.sql).
--
-- ─── 1) anchor 재조정 ────────────────────────────────────
--   최상  1.75 → 1.0      중하  -0.25 → -0.4
--   상    1.25 → 0.7      하    -0.75 → -0.7
--   중상  0.75 → 0.4      최하  -1.25 → -1.0
--   중    0.25 → 0
--
-- '중' 이 정확히 0 에 놓여 좌우 대칭이 됩니다. 간격은 일정하지 않습니다
-- (중↔중상 0.4, 그 위는 0.3씩) — 가운데가 넓고 끝으로 갈수록 촘촘합니다.
--
-- ⚠ **tier_step(0.50) 은 함께 조정하지 않았습니다** (요청 범위가 아니라서).
--   이 값은 두 곳에 쓰입니다:
--     · 수렴도 = max(0, 1 - 표준편차 / tier_step) 의 분모
--     · 투표 슬라이더의 step (tierStep / 2 = 0.25, ChartDetailPanel)
--   새 anchor 최소 간격(0.3)보다 커서 (1) 수렴도가 실제보다 후하게 나오고
--   (2) 슬라이더가 0.25 눈금이라 0.4 · 0.7 · -0.4 · -0.7 에 정확히 멈추지
--   못합니다. 투표는 최근접 anchor 로 버킷팅되므로 일곱 등급 모두 도달은
--   가능하지만, 눈금과 등급이 어긋납니다. 눈금을 맞추려면 tier_step 을
--   0.30 으로 내리는 것을 고려하세요 (수렴도 기준도 함께 엄격해집니다).
--
-- ⚠ vote_min/vote_max(-1.25 ~ 1.75) 도 그대로입니다. anchor 범위(-1 ~ 1) 보다
--   넓고 위아래가 비대칭이라, 슬라이더 양 끝에 등급이 없는 구간이 생깁니다.
--
-- ─── 2) 수렴도 임계값 0.20 → 0.30 ────────────────────────
-- 이 값 미만이면 등급 대신 '개인차' 로 갑니다. 올렸으니 의견이 갈리는 채보가
-- 더 잘 걸러집니다.
--
-- ─── 3) 가상 투표 삭제 (Bad Apple 만 남김) ────────────────
-- 012 가 넣은 S1 투표는 **옛 anchor(중 = 0.25)에 맞춰 만든 값**입니다. anchor 가
-- 바뀌면 근거 없는 숫자가 되므로 지웁니다. `Bad Apple!! feat. nomico` 한 곡만
-- 남겨 집계 파이프라인이 동작하는 예시로 씁니다.
--
-- ⚠ **Bad Apple 의 등급이 '중' 에서 '중상' 으로 올라갑니다.** 투표를 그대로
--   두라고 하셨으니 값은 손대지 않았는데, 평균 0.26 이 새 anchor 기준으로는
--   중(0) 보다 중상(0.4) 에 더 가깝습니다 (0.26 vs 0.14). 원래 자리인 '중' 에
--   두려면 이 곡의 투표를 0 중심으로 다시 만들어야 합니다.
--
-- ⚠ **clear_records 는 남깁니다.** 요청은 '투표' 였고 이 스키마에서 클리어
--   기록은 별개 개념입니다(화면에도 따로 표시됨). "클리어했지만 아직 투표 안 함"
--   상태가 되어, 그 계정들이 나중에 투표할 수 있습니다.
--
-- ⚠ **사볼 투표는 남깁니다.** 이 파일은 펌프 등급 스케일 작업이고, 사볼까지
--   지우면 그쪽 서열표가 통째로 비어 게임 선택기에서 고를 수 없는 항목이 됩니다.
--
-- ─── 4) '고유' → '개인차' 명칭 변경 ──────────────────────
-- 이건 화면 문구라 DB 가 아니라 코드에 있습니다 (lib/tier.ts · ChartDetailPanel).
-- charts.tier_code 에 저장되는 값은 'unique' 그대로 둡니다 — 저장값을 바꾸면
-- 이미 그 등급인 행을 함께 마이그레이션해야 하고, 얻는 것이 없습니다.
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- UPDATE 는 고정값이고, DELETE 는 지울 것이 없으면 0행입니다.
--
-- 되돌리려면: 투표는 복구할 수 없습니다 (지워진 값입니다).
--   anchor/임계값만 되돌리려면 seed-tier.sql 의 옛 값으로 UPDATE 하세요.
-- ============================================================

-- ─── 1) anchor ─────────────────────────────────────────────
UPDATE tier_grades g SET anchor = v.anchor
FROM (VALUES
  ('ss',  1.0), ('s',   0.7), ('a',  0.4), ('b', 0),
  ('c',  -0.4), ('d',  -0.7), ('dd', -1.0)
) AS v(code, anchor)
WHERE g.machine_id = 1 AND g.code = v.code;

-- ─── 2) 수렴도 임계값 ──────────────────────────────────────
UPDATE tier_settings SET min_convergence = 0.30 WHERE machine_id = 1;

-- ─── 3) 가상 투표 삭제 (Bad Apple 제외) ────────────────────
DELETE FROM difficulty_votes v
USING charts c, songs s
WHERE c.id = v.chart_id
  AND s.id = c.song_id
  AND s.machine_id = 1
  AND s.title <> 'Bad Apple!! feat. nomico';

-- ─── 4) 재집계 ─────────────────────────────────────────────
-- anchor 가 바뀌었으므로 투표가 남아 있는 채보도 등급을 다시 계산해야 합니다.
SELECT recalc_chart_stats(c.id)
FROM charts c JOIN songs s ON s.id = c.song_id
WHERE s.machine_id = 1;
