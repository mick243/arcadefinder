-- ============================================================
-- 046 · 사볼 평가에서 펌프 전용 태그 정리
--
-- ─── 무엇이 바뀌나 ───────────────────────────────────────
-- 채보 성향 태그를 게임별 목록으로 나눴습니다
-- (lib/community-types.ts CHART_TAGS_BY_MACHINE).
--
--   펌프 — 지금까지 그대로 (폭타 · 떨기 · 틀기 · 연타 · 체중이동 · 체력 · …)
--   사볼 — 발판 용어를 빼고 손 쪽 용어로
--          빠짐 : 떨기 · 틀기 · 체중이동 · 체력
--          들어감: 지력 · 건반 · 노브 · 트릴
--
-- 목록은 코드에 있으므로(집계용 고정 목록이라 DB 테이블이 아닙니다) 이 파일이
-- 하는 일은 **사볼 평가에 남아 있는 펌프 전용 태그를 지우는 것**뿐입니다.
-- 적용 시점의 대상은 시드가 넣은 사볼 평가의 '체력' 1건입니다.
--
-- ─── 왜 지워야 하나 ──────────────────────────────────────
-- 평가 폼은 저장된 태그를 그대로 불러오는데(ChartComments.tsx setTags),
-- 사볼 화면에는 '체력' 칩이 더 이상 없습니다. 그러면 그 태그는 **화면에 안 보이는
-- 채로 폼에 남아** 다시 저장할 때 조용히 따라 들어갑니다. 지우는 편이 정직합니다.
--
-- (저장 검증은 합집합이라 막히지는 않습니다 — migrate-036 때와 달리 "수정이
--  불가능해지는" 문제는 없습니다. 그래도 안 보이는 값이 남는 것은 같습니다.)
--
-- ─── 지우기만 하고 갈아끼우지 않습니다 ───────────────────
-- '체력' 과 '지력' 은 글자만 비슷하지 뜻이 다릅니다 — 체력은 몸이 버티느냐,
-- 지력은 종합적인 처리 능력입니다. 임의로 대응시키면 남이 쓴 평가의 내용을
-- 바꾸는 셈이라 지우기만 합니다. 본문은 건드리지 않습니다.
--
-- ⚠ **updated_at 은 올리지 않습니다.** 목록이 timeAgo(updatedAt) 를 보여주므로
--   올리면 작성자가 방금 고친 것처럼 보입니다 (migrate-036 과 같은 이유).
--
-- ─── 여러 번 실행해도 결과가 같습니다 ────────────────────
-- 두 번째 실행에는 걸리는 행이 없습니다 (WHERE tags && …).
--
-- 되돌릴 수 없습니다 — 지운 태그는 복구되지 않습니다.
-- ============================================================

UPDATE chart_comments cc SET
  tags = ARRAY(
    SELECT t FROM unnest(cc.tags) AS t
     WHERE t <> ALL (ARRAY['떨기', '틀기', '체중이동', '체력'])
  )
FROM charts c
JOIN songs s ON s.id = c.song_id
WHERE c.id = cc.chart_id
  AND s.machine_id = 3
  AND cc.tags && ARRAY['떨기', '틀기', '체중이동', '체력'];
