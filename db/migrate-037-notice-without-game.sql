-- 공지는 게임 없이 쓸 수 있다 (posts.machine_id NULL 허용)
--
-- 지금까지 모든 글은 게임 하나에 속했습니다 (schema-board.sql 의 판단). 공지는
-- 그 전제에서 벗어납니다 — 커뮤니티 전체의 알림이라 모든 게임 탭 맨 위에 붙고
-- (lib/board.ts listPosts), "어느 게시판에 썼는지" 가 읽는 사람에게 뜻이 없습니다.
-- 그런 글에 게임을 억지로 고르게 하면, 저장된 값이 아무 의미 없는 잡음이 됩니다.
--
-- NULL = 게임에 속하지 않는 글. 지금은 공지만 그렇고, 그 규칙은 코드가 지킵니다
-- (lib/validation.ts postInputSchema — 공지가 아니면 게임 필수).
--
-- ⚠ CHECK 제약으로 "공지만 NULL" 을 DB 에 박지 않았습니다. 말머리는 배포 없이
--   늘릴 수 있는 테이블 값인데(board_categories), 그 값을 참조하는 제약을 걸면
--   말머리를 하나 추가·삭제할 때마다 마이그레이션이 필요해집니다.
--
-- ⚠ 여러 번 실행해도 안전해야 합니다 (lib/db.ts runMigrations 주석 참고).
--   DROP NOT NULL 은 이미 없으면 아무 일도 하지 않습니다 — 그래서 이 파일이
--   017 번으로 먼저 배포됐던 DB(이력에 그 이름이 남아 있는 DB)에서 다시 돌아도
--   결과가 같습니다.
-- ============================================================

ALTER TABLE posts ALTER COLUMN machine_id DROP NOT NULL;
